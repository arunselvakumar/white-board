import ExcelJS from "exceljs";
import {
  decodePDFRawStream,
  PDFArray,
  PDFDict,
  PDFDocument,
  PDFName,
  PDFRawStream,
  type PDFPage,
} from "pdf-lib";
import sharp from "sharp";
import { describe, expect, it } from "vitest";

import { column, type ReportDocument } from "../domain/report-document";
import { printableImage } from "./dpr-images";
import type { DprImageLoader } from "./dpr-pdf";
import { needsNoto, renderPdf } from "./pdf-report";
import { renderXlsx } from "./xlsx-report";

const GENERATED = "Generated by Asha Rao on 16 Oct 2026, 14:05";

function report(overrides: Partial<ReportDocument["header"]> = {}) {
  const rows = Array.from({ length: 80 }, (_, index) => [
    `Labour ${String(index + 1)}`,
    index,
  ]);
  const document: ReportDocument = {
    header: {
      company: "Anugraha Engineers",
      title: "All Labour Attendance",
      project: "Tower A",
      address: null,
      period: "01 Sep 2026 to 30 Sep 2026",
      generated: GENERATED,
      logo: null,
      currency: "INR",
      ...overrides,
    },
    notes: [],
    tables: [
      {
        name: "Summary",
        columns: [column("Labour", "text"), column("Present", "count")],
        rows,
        totals: null,
      },
    ],
    pageSize: "a4",
    fileName: "all-labour-attendance",
  };
  return document;
}

/** A page's drawing operators, decoded. */
function contentOf(page: PDFPage): string {
  const contents = page.node.Contents();
  const streams =
    contents instanceof PDFArray
      ? contents.asArray().map((ref) => page.doc.context.lookup(ref))
      : [contents];
  return streams
    .map((stream) =>
      stream instanceof PDFRawStream
        ? new TextDecoder().decode(decodePDFRawStream(stream).decode())
        : "",
    )
    .join("\n");
}

/** How the standard fonts write `text` in a content stream. */
function hexOf(text: string): string {
  return Buffer.from(text, "latin1").toString("hex").toUpperCase();
}

function images(pdf: PDFDocument): number {
  return pdf.context
    .enumerateIndirectObjects()
    .filter(
      ([, object]) =>
        object instanceof PDFRawStream &&
        object.dict.get(PDFName.of("Subtype")) === PDFName.of("Image"),
    ).length;
}

async function png(): Promise<Uint8Array> {
  return new Uint8Array(
    await sharp({
      create: {
        width: 120,
        height: 60,
        channels: 4,
        background: { r: 20, g: 90, b: 160, alpha: 1 },
      },
    })
      .png()
      .toBuffer(),
  );
}

describe("the report PDF header and footer (ADR CM-0021 §2)", () => {
  it("prints Generated by on every page's footer, not in the header", async () => {
    const pdf = await PDFDocument.load(await renderPdf(report()));
    expect(pdf.getPageCount()).toBeGreaterThan(1);
    for (const page of pdf.getPages()) {
      const content = contentOf(page);
      expect(content).toContain(hexOf(GENERATED));
      expect(content).not.toContain(hexOf("Generated at"));
    }
    expect(images(pdf)).toBe(0);
  });

  it("uses the Noto fonts when a name is in an Indian script, so it never prints as ?", async () => {
    const pdf = await PDFDocument.load(
      await renderPdf(
        report({ generated: "Generated by அருண் on 16 Oct 2026, 14:05" }),
      ),
    );
    const fonts = pdf.context
      .enumerateIndirectObjects()
      .flatMap(([, object]) =>
        object instanceof PDFDict &&
        object.get(PDFName.of("Type")) === PDFName.of("Font")
          ? [String(object.get(PDFName.of("BaseFont")))]
          : [],
      )
      .join(" ");
    expect(fonts).toContain("NotoSansTamil");
    expect(needsNoto(["Rs. 1,00,000 – Tower A"])).toBe(false);
    expect(needsNoto(["₹1,00,000"])).toBe(false);
  });

  it("prints the header logo on every page from storage", async () => {
    const bytes = await png();
    const loads: string[] = [];
    const loader: DprImageLoader = async (ref, use) => {
      loads.push(`${use}:${ref.key}`);
      return printableImage(bytes, use);
    };
    const rendered = await renderPdf(
      report({
        logo: { key: "companies/ws/logos/a.png", contentType: "image/png" },
      }),
      loader,
    );
    const pdf = await PDFDocument.load(rendered);
    expect(loads).toEqual(["logo:companies/ws/logos/a.png"]);
    // Embedded once, drawn on each page.
    expect(images(pdf)).toBe(1);
    for (const page of pdf.getPages()) expect(contentOf(page)).toMatch(/ Do\b/);
  });

  it("prints no logo when it cannot be read", async () => {
    const pdf = await PDFDocument.load(
      await renderPdf(
        report({ logo: { key: "missing", contentType: "image/png" } }),
        () => Promise.resolve(null),
      ),
    );
    expect(images(pdf)).toBe(0);
  });
});

describe("the report workbook's Generated by line", () => {
  it("sits under the header block of every sheet", async () => {
    const workbook = new ExcelJS.Workbook();
    await workbook.xlsx.load(
      Buffer.from(await renderXlsx(report())) as unknown as ArrayBuffer,
    );
    const sheet = workbook.worksheets[0];
    const values: unknown[] = [];
    sheet?.eachRow((row) => {
      values.push((row.values as unknown[])[1]);
    });
    expect(values.slice(0, 5)).toEqual([
      "Anugraha Engineers",
      "All Labour Attendance - Summary",
      "Project",
      "Period",
      GENERATED,
    ]);
    expect(values).not.toContain("Generated at");
  });
});
