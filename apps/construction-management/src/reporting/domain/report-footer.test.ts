import { describe, expect, it } from "vitest";

import { generatedAtText, generatedByLine } from "./report-footer";

describe("the Generated by line (ADR CM-0021 §2)", () => {
  it("names the requester and the time in the Company's time zone, 24-hour", () => {
    expect(
      generatedByLine(
        "Asha Rao",
        new Date("2026-10-16T08:35:00Z"),
        "Asia/Kolkata",
      ),
    ).toBe("Generated by Asha Rao on 16 Oct 2026, 14:05");
  });

  it("prints the day without a leading zero and midnight as 00", () => {
    expect(
      generatedAtText(new Date("2026-10-05T18:30:00Z"), "Asia/Kolkata"),
    ).toBe("6 Oct 2026, 00:00");
    expect(generatedAtText(new Date("2026-09-30T23:59:00Z"), "UTC")).toBe(
      "30 Sep 2026, 23:59",
    );
  });

  it("uses another Company's zone, and India when the zone is not valid", () => {
    expect(
      generatedAtText(new Date("2026-10-16T08:35:00Z"), "Asia/Dubai"),
    ).toBe("16 Oct 2026, 12:35");
    expect(generatedAtText(new Date("2026-10-16T08:35:00Z"), "Mars/Base")).toBe(
      "16 Oct 2026, 14:05",
    );
  });

  it("leaves the name out when there is none", () => {
    expect(
      generatedByLine(null, new Date("2026-10-16T08:35:00Z"), "Asia/Kolkata"),
    ).toBe("Generated on 16 Oct 2026, 14:05");
    expect(
      generatedByLine("  ", new Date("2026-10-16T08:35:00Z"), "Asia/Kolkata"),
    ).toBe("Generated on 16 Oct 2026, 14:05");
  });
});
